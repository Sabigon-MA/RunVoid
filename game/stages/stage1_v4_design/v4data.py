# 地形の層（描画・地図の色分け用）
UPPER, MID, LOWER, DEEP = "upper", "mid", "lower", "deep"


def S(id, x0, x1, top, bottom=WORLD_BOTTOM, layer=MID, style="ground", note=""):
    """固体の地形（左右・上下から通れない）。bottom の既定値はワールドの下端。"""
    return {"id": id, "kind": "solid", "x0": x0, "x1": x1, "top": top, "bottom": bottom,
            "layer": layer, "style": style, "note": note}


def O(id, x0, x1, top, layer=UPPER, note=""):
    """すり抜け足場（下からは通れ、上に乗れる。S＋Space で降りる）。厚さ 16。"""
    return {"id": id, "kind": "oneway", "x0": x0, "x1": x1, "top": top, "bottom": top + 16,
            "layer": layer, "style": "ground", "note": note}


def GATE(id, x0, x1, note=""):
    return {"id": id, "kind": "solid", "x0": x0, "x1": x1, "top": GATE_TOP, "bottom": WORLD_BOTTOM,
            "layer": "gate", "style": "sealed_gate", "note": note}


